class ProfileError(Exception):
    """Raised when the source data is inconsistent or cannot be read."""


@dataclass
class Firmware:
    verdict: str
    confidence: str
    mod_links: list[str]
    sources: list[str]


@dataclass
class Model:
    name: str
    nozzles: set[str] = field(default_factory=set)
    presets: int = 0
    firmware: Firmware | None = None


@dataclass
class Vendor:
    name: str
    models: list[Model]


# ---------------------------------------------------------------------------
# Source repository access (read-only, committed HEAD only)
# ---------------------------------------------------------------------------


def git(source: Path, *args: str) -> bytes:
    try:
        result = subprocess.run(
            ["git", "-C", str(source), *args],
            check=False,
            capture_output=True,
        )
    except OSError as exc:
        raise ProfileError(f"cannot run git: {exc}") from exc
    if result.returncode != 0:
        message = result.stderr.decode("utf-8", "replace").strip()
        raise ProfileError(f"git {' '.join(args)} failed in {source}: {message}")
    return result.stdout


def source_commit(source: Path) -> str:
    return git(source, "rev-parse", "--short=10", "HEAD").decode("ascii").strip()


def export_profiles(source: Path, commit: str, target: Path) -> Path:
    """Extract resources/profiles at `commit` into `target`; return the profiles dir."""
    archive = git(source, "archive", "--format=tar", commit, PROFILES_PATH)
    with tarfile.open(fileobj=io.BytesIO(archive), mode="r:") as tar:
        tar.extractall(target, filter="data")
    profiles = target / PROFILES_PATH
    if not profiles.is_dir():
        raise ProfileError(f"{PROFILES_PATH} missing at {commit}; --source must be a KLIPSLICE repository")
    return profiles


