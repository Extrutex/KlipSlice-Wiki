#!/usr/bin/env python3
"""Generate the "Supported printers" pages from a KLIPSLICE source repository.

Everything is read from the committed HEAD of the source repository, never from
its working tree, so the pages always match exactly one source commit:

- resources/profiles/<Vendor>.json and the machine presets they index. Every
  instantiable printer preset is resolved through its `inherits` chain.
- docs/klipslice/printer-firmware.json, the per-model firmware evidence
  (Klipper/Moonraker status, community mod project, sources).

One Markdown page is written per wiki language (docs/printers.md and
docs/printers.de.md).

The run aborts on any inconsistency, because the page must never list a printer
KLIPSLICE does not target:

- an instantiable preset whose gcode_flavor is not `klipper`,
- a profile model without a firmware entry, or whose entry is not `kept`,
- a `kept` firmware entry without a profile model,
- a kept entry with a verdict that is not a known Klipper status.

Usage:
    python3 scripts/gen_printers.py --source /path/to/KLIPSLICE --docs docs
    python3 scripts/gen_printers.py --source /path/to/KLIPSLICE --docs docs --check

--check writes nothing and exits 1 if the committed pages differ from what the
source commit generates. Requires `git` on PATH.
"""

