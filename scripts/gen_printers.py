def parse_firmware(raw: bytes) -> dict[str, Firmware]:
    """Return the kept firmware entries keyed by model name."""
    try:
        entries = json.loads(raw)
    except json.JSONDecodeError as exc:
        raise ProfileError(f"{FIRMWARE_PATH}: invalid JSON: {exc}") from exc
    if not isinstance(entries, list):
        raise ProfileError(f"{FIRMWARE_PATH}: top level is not a JSON array")

    seen: set[str] = set()
    kept: dict[str, Firmware] = {}
    for position, entry in enumerate(entries):
        where = f"{FIRMWARE_PATH}[{position}]"
        if not isinstance(entry, dict):
            raise ProfileError(f"{where}: entry is not an object")
        missing = [key for key in FIRMWARE_KEYS if key not in entry]
        if missing:
            raise ProfileError(f"{where}: missing keys {missing}")
        model = entry["model"]
        if not isinstance(model, str) or not model:
            raise ProfileError(f"{where}: 'model' must be a non-empty string")
        if model in seen:
            raise ProfileError(f"{where}: duplicate model '{model}'")
        seen.add(model)
        if not isinstance(entry["kept"], bool):
            raise ProfileError(f"{where} ({model}): 'kept' must be true or false")
        if not entry["kept"]:
            continue

        verdict = entry["verdict"]
        if verdict not in VERDICTS:
            raise ProfileError(f"{where} ({model}): kept with verdict {verdict!r}, expected one of {VERDICTS}")
        confidence = entry["confidence"]
        if confidence not in CONFIDENCES:
            raise ProfileError(f"{where} ({model}): unknown confidence {confidence!r}")
        sources = entry["sources"]
        if not isinstance(sources, list) or not sources:
            raise ProfileError(f"{where} ({model}): a kept model needs at least one source")
        for url in sources:
            if not isinstance(url, str) or URL_PATTERN.fullmatch(url) is None:
                raise ProfileError(f"{where} ({model}): source {url!r} is not a plain http(s) URL")
        mod_project = entry["mod_project"]
        if not isinstance(mod_project, str):
            raise ProfileError(f"{where} ({model}): 'mod_project' must be a string")
        mod_links = unique(URL_PATTERN.findall(mod_project))
        if verdict == "KLIPPER_VIA_ESTABLISHED_MOD" and not mod_links:
            raise ProfileError(f"{where} ({model}): verdict {verdict} needs a mod project URL")
        kept[model] = Firmware(verdict, confidence, mod_links, list(sources))
    return kept


def unique(items: list[str]) -> list[str]:
    result: list[str] = []
    for item in items:
        if item not in result:
            result.append(item)
    return result


def attach_firmware(vendors: list[Vendor], firmware: dict[str, Firmware]) -> None:
    listed: set[str] = set()
    for vendor in vendors:
        for model in vendor.models:
            entry = firmware.get(model.name)
            if entry is None:
                raise ProfileError(
                    f"{vendor.name}: model '{model.name}' has a profile but no kept entry in {FIRMWARE_PATH}"
                )
            model.firmware = entry
            listed.add(model.name)
    orphaned = sorted(set(firmware) - listed, key=str.casefold)
    if orphaned:
        raise ProfileError(f"kept in {FIRMWARE_PATH} but no printer profile: {', '.join(orphaned)}")


