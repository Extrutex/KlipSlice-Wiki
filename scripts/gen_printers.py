def anchor(name: str) -> str:
    slug = "".join(ch if ch.isalnum() else "-" for ch in name.casefold())
    while "--" in slug:
        slug = slug.replace("--", "-")
    return "vendor-" + slug.strip("-")


def cell(text: str) -> str:
    return text.replace("|", "\\|")


def host_label(url: str) -> str:
    host = urlsplit(url).hostname or url
    return host[4:] if host.startswith("www.") else host


def link_label(url: str) -> str:
    parts = urlsplit(url)
    segments = [segment for segment in parts.path.split("/") if segment]
    if parts.hostname == "github.com" and len(segments) >= 2:
        return f"{segments[0]}/{segments[1]}"
    return host_label(url)


def link_list(urls: list[str], label) -> str:
    labels = [label(url) for url in urls]
    rendered = []
    for position, (url, text) in enumerate(zip(urls, labels)):
        if labels.count(text) > 1:
            text = f"{text} ({labels[:position + 1].count(text)})"
        rendered.append(f"[{cell(text)}]({url})")
    return "<br>".join(rendered)


def render(vendors: list[Vendor], lang: str, commit: str) -> str:
    t = TEXT[lang]
    models = [model for vendor in vendors for model in vendor.models]
    preset_total = sum(model.presets for model in models)
    status_counts = {verdict: 0 for verdict in VERDICTS}
    for model in models:
        status_counts[model.firmware.verdict] += 1

    lines = [
        "<!-- Generated by scripts/gen_printers.py. Do not edit by hand. -->",
        "",
        f"# {t['title']}",
        "",
        t["intro"],
        "",
        f"!!! info \"{t['moonraker_title']}\"",
        "",
        f"    {t['moonraker']}",
        "",
        t["klipper_only"],
        "",
        f"## {t['summary_title']}",
        "",
        f"| {t['vendors']} | {t['models']} | {t['presets']} |",
        "|---:|---:|---:|",
        f"| {len(vendors)} | {len(models)} | {preset_total} |",
        "",
        f"| {t['status_col']} | {t['count_col']} |",
        "|---|---:|",
    ]
    for verdict in VERDICTS:
        lines.append(f"| {t['verdicts'][verdict]} | {status_counts[verdict]} |")
    lines += [
        "",
        f"| {t['vendor_col']} | {t['count_col']} |",
        "|---|---:|",
    ]
    for vendor in vendors:
        lines.append(f"| [{cell(vendor.name)}](#{anchor(vendor.name)}) | {len(vendor.models)} |")
    lines += [
        "",
        f"## {t['legend_title']} {{ #firmware-status }}",
        "",
        t["legend_intro"],
        "",
    ]
    for verdict in VERDICTS:
        lines += [f"{t['verdicts'][verdict]}", f":   {t['verdict_help'][verdict]}", ""]
    lines += [f"{t['confidence_title']}", f":   {t['confidence_help']}", ""]
    lines += [f"## {t['own_title']} {{ #own-printer }}", "", *t["own"], ""]

    header = (
        f"| {t['model_col']} | {t['nozzle_col']} | {t['firmware_col']} | {t['mod_col']} "
        f"| {t['confidence_col']} | {t['sources_col']} |"
    )
    for vendor in vendors:
        lines += [f"## {vendor.name} {{ #{anchor(vendor.name)} }}", "", header, "|---|---|---|---|---|---|"]
        for model in vendor.models:
            fw = model.firmware
            nozzles = ", ".join(sorted(model.nozzles, key=nozzle_sort_key))
            mods = link_list(fw.mod_links, link_label) if fw.mod_links else "–"
            lines.append(
                f"| {cell(model.name)} | {nozzles} | {t['verdicts'][fw.verdict]} | {mods} "
                f"| {t['confidences'][fw.confidence]} | {link_list(fw.sources, link_label)} |"
            )
        lines.append("")
    lines += [f"<small>{t['generated_from']} `{commit}`.</small>", ""]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--source", required=True, type=Path, help="path to a KLIPSLICE source repository")
    parser.add_argument("--docs", required=True, type=Path, help="wiki docs directory to write into")
    parser.add_argument("--check", action="store_true", help="compare only, write nothing; exit 1 on difference")
    args = parser.parse_args()

    if not args.docs.is_dir():
        print(f"error: {args.docs} is not a directory", file=sys.stderr)
        return 2
    try:
        commit = source_commit(args.source)
        with tempfile.TemporaryDirectory(prefix="gen_printers_") as scratch:
            vendors = collect_profiles(export_profiles(args.source, commit, Path(scratch)))
        firmware = parse_firmware(git(args.source, "show", f"{commit}:{FIRMWARE_PATH}"))
        attach_firmware(vendors, firmware)
    except ProfileError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1

    stale = []
    for lang, filename in OUTPUT_NAMES.items():
        target = args.docs / filename
        content = render(vendors, lang, commit)
        if args.check:
            current = target.read_text(encoding="utf-8") if target.is_file() else None
            if current != content:
                stale.append(str(target))
        else:
            target.write_text(content, encoding="utf-8")
            print(f"wrote {target}")
    if stale:
        print("out of date: " + ", ".join(stale), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
